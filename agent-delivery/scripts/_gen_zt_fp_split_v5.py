def norm(s: str) -> str:
    return re.sub(r"\s+", "", str(s or "").strip())


def load_function_tree() -> list[dict]:
    wb = openpyxl.load_workbook(SRC, data_only=True, read_only=True)
    ws = wb["科技专题服务系统"]
    rows = list(ws.iter_rows(values_only=True))
    header_idx = 0
    for i, row in enumerate(rows[:5]):
        if "需规功能描述" in "".join(str(x or "") for x in row[:14]):
            header_idx = i
            break
    cur = [""] * 6
    items = []
    for row in rows[header_idx + 1 :]:
        vals = list(row) + [None] * 20
        levels = [norm(vals[idx]) if vals[idx] else "" for idx in (6, 7, 8, 9, 10, 11)]
        for j, v in enumerate(levels):
            if v:
                cur[j] = v
                for k in range(j + 1, 6):
                    cur[k] = ""
        if cur[3] not in L4_TARGETS:
            continue
        desc = str(vals[12]).strip() if vals[12] else ""
        if not (cur[4] or cur[5] or desc):
            continue
        items.append({"l4": cur[3], "l5": cur[4] or "/", "l6": cur[5] or "/", "desc": desc})
    wb.close()
    return items


def build_rows(items: list[dict]) -> list[dict]:
    rows = []
    missing = []
    for it in items:
        key = (it["l5"], it["l6"])
        fps = HAND_SPLITS.get(key)
        if not fps:
            missing.append(key)
            continue
        for fp in fps:
            rows.append(
                {
                    "功能模块": MODULE,
                    "子功能模块": it["l4"],
                    "功能项": it["l5"],
                    "子功能项": it["l6"],
                    "页面": it["l5"],
                    "功能点": fp,
                    "需规描述": it["desc"],
                }
            )
    if missing:
        raise SystemExit("未覆盖的六级功能: " + "; ".join(f"{a}/{b}" for a, b in missing))
    return rows


def write_excel(rows: list[dict]) -> None:
    wb = openpyxl.load_workbook(TPL)
    ws = wb["功能测试用例"]
    ws["A1"] = A1_TITLE
    if ws.max_row > 2:
        ws.delete_rows(3, ws.max_row - 2)
    for rng in list(ws.merged_cells.ranges):
        if str(rng).startswith("A1:"):
            ws.unmerge_cells(str(rng))
    ws.insert_cols(8)
    ws.merge_cells("A1:R1")
    ws["A1"] = A1_TITLE
    headers = [
        "用例编号",
        "功能模块",
        "子功能模块",
        "功能项",
        "子功能项",
        "页面",
        "功能点",
        "需规描述",
        "测试内容",
        "前置条件",
        "测试步骤",
        "预期结果",
        "优先级",
        "是否通过",
        "测试工程师",
        "测试时间",
        "审核员",
        "测试截图",
    ]
    for col, h in enumerate(headers, start=1):
        cell = ws.cell(2, col, h)
        cell.font = Font(bold=True)
    align = Alignment(wrap_text=True, vertical="top")
    for i, r in enumerate(rows, start=1):
        rec = {
            "用例编号": f"ZNFWJQ-KJZTFWXT-v1.0-FUNC-{i:05d}",
            **r,
        }
        for col, h in enumerate(headers, start=1):
            cell = ws.cell(i + 2, col, rec.get(h, "") or "")
            cell.alignment = align
    widths = [36, 18, 16, 22, 22, 20, 36, 56]
    for col, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(col)].width = w
    for name in wb.sheetnames:
        if name in ("功能测试用例", "规则 -0529"):
            continue
        wso = wb[name]
        if wso.max_row > 2:
            wso.delete_rows(3, wso.max_row - 2)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUT)
    wb.close()


